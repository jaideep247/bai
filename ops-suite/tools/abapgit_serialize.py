#!/usr/bin/env python3
"""Generate abapGit metadata for ops-suite/src so the repository can be pulled
with abapGit (folder logic PREFIX, starting folder /ops-suite/src/).

Creates / refreshes:
  ../.abapgit.xml                          repository settings (repo root)
  src/package.devc.xml, src/<mod>/...      packages ZCD_OPS, ZCD_OPS_<MOD>
  src/**/<obj>.clas.xml|intf.xml|prog.xml  object metadata (description = ABAP Doc shorttext)
  src/<mod>/<tab>.tabl.xml                 tables, from ddic/<mod>/<tab>.tabl.ddl (incl. draft tables)
  src/**/<obj>.ddls|ddlx|bdef|srvd.xml     RAP sources (generated by tools/rap_generate.py or hand-written)
  src/**/<obj>.dcls.xml                    access controls (DCL roles, .asdcls source)
  behaviour pools (FOR BEHAVIOR OF)        CATEGORY 06 + CLSDEFINT
  src/core/zcd_ops.msag.xml                message class, from config/zcd_ops_messages.md

Re-run after adding objects, tables or messages:  python3 tools/abapgit_serialize.py
Secondary indexes: DDL comment lines '// @index <ID> [UNIQUE]: F1, F2' -> DD12V/DD17V.
Audit A89: every output is staged in memory and validated first; files are replaced only
when all tables serialized cleanly (exit 1 and nothing written otherwise). Unchanged
files are never rewritten.
"""
import os, re, sys
from xml.sax.saxutils import escape

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'src')
HEAD = '<?xml version="1.0" encoding="utf-8"?>\n'
PACKAGES = {'': ('ZCD_OPS', 'Payment engine operations suite'),
            'core': ('ZCD_OPS_CORE', 'Ops suite: store, alerting, factory'),
            'ebs': ('ZCD_OPS_EBS', 'Ops suite: EBS validation (BAI2 / CAMT)'),
            'fmon': ('ZCD_OPS_FMON', 'Ops suite: file monitoring'),
            'hck': ('ZCD_OPS_HCK', 'Ops suite: health check, morning report')}

def wrap(serializer, body):
    return (HEAD + f'<abapGit version="v1.0.0" serializer="{serializer}" serializer_version="v1.0.0">\n'
            ' <asx:abap xmlns:asx="http://www.sap.com/abapxml" version="1.0">\n  <asx:values>\n'
            + body + '  </asx:values>\n </asx:abap>\n</abapGit>\n')

def tag(name, value, indent=4):
    return ' ' * indent + f'<{name}>{escape(str(value))}</{name}>\n'

PENDING = {}  # path -> text, flushed only after every input validated (audit A89)


def write(path, text):
    """Stage one output; returns 1 if it differs from the file on disk."""
    PENDING[path] = text
    if not os.path.exists(path) or open(path, encoding='utf-8').read() != text:
        return 1
    return 0


def flush():
    for path, text in PENDING.items():
        if not os.path.exists(path) or open(path, encoding='utf-8').read() != text:
            open(path, 'w', encoding='utf-8', newline='\n').write(text)

def description(text, default):
    m = re.search(r'shorttext synchronized">([^<]*)<', text)
    return (m.group(1) if m else default)[:60]

changed = 0
# repository settings
changed += write(os.path.join(os.path.dirname(ROOT), '.abapgit.xml'), HEAD +
    '<asx:abap xmlns:asx="http://www.sap.com/abapxml" version="1.0">\n <asx:values>\n  <DATA>\n'
    '   <MASTER_LANGUAGE>E</MASTER_LANGUAGE>\n   <STARTING_FOLDER>/ops-suite/src/</STARTING_FOLDER>\n'
    '   <FOLDER_LOGIC>PREFIX</FOLDER_LOGIC>\n   <IGNORE>\n    <item>/.gitignore</item>\n'
    '    <item>/LICENSE</item>\n    <item>/README.md</item>\n'
    '   </IGNORE>\n  </DATA>\n </asx:values>\n</asx:abap>\n')

# packages
for folder, (_, text) in PACKAGES.items():
    path = os.path.join(SRC, folder, 'package.devc.xml')
    changed += write(path, wrap('LCL_OBJECT_DEVC', '   <DEVC>\n' + tag('CTEXT', text) + '   </DEVC>\n'))

def tpool(texts):
    """TPOOL of a program or class from docs/text_elements/<object>.texts.md (empty if none)."""
    if not os.path.exists(texts):
        return ''
    out = '   <TPOOL>\n'
    kinds = {'Title': 'R', 'Text symbol': 'I', 'Selection text': 'S'}
    for kind, key, text in re.findall(r'^\| (Title|Text symbol|Selection text) \| (\S+) \| (.*?) \|$',
                                      open(texts, encoding='utf-8').read(), re.M):
        entry = (' ' * 8 + text) if kinds[kind] == 'S' else text
        out += '    <item>\n' + tag('ID', kinds[kind], 5)
        if kinds[kind] != 'R':
            out += tag('KEY', key, 5)
        out += tag('ENTRY', entry, 5) + tag('LENGTH', len(entry), 5) + '    </item>\n'
    return out + '   </TPOOL>\n'


# classes, interfaces, programs
for d, _, files in os.walk(SRC):
    for f in sorted(files):
        p = os.path.join(d, f)
        name = f.split('.')[0].upper()
        if f.endswith('.clas.abap'):
            text = open(p, encoding='utf-8').read()
            body = '   <VSEOCLASS>\n' + tag('CLSNAME', name) + tag('LANGU', 'E') + \
                   tag('DESCRIPT', description(text, name))
            behavior = re.search(r'FOR\s+BEHAVIOR\s+OF\s+(\w+)', text, re.I)
            if name.startswith('ZCX_'):
                body += tag('CATEGORY', '40')
            elif behavior:  # RAP behaviour pool (sample: abap-platform-refscen-flight, 2023)
                body += tag('CATEGORY', '06')
            body += tag('STATE', '1') + tag('CLSCCINCL', 'X') + tag('FIXPT', 'X') + tag('UNICODE', 'X')
            if behavior:
                body += tag('CLSDEFINT', behavior.group(1).upper())
            if os.path.exists(p.replace('.clas.abap', '.clas.testclasses.abap')):
                body += tag('WITH_UNIT_TESTS', 'X')
            body += '   </VSEOCLASS>\n'
            # Class text pool (text symbols TEXT-nnn), same TPOOL format as programs and
            # placed right after VSEOCLASS as in abapGit's zcl_abapgit_object_clas->serialize_xml
            body += tpool(os.path.join(ROOT, 'docs', 'text_elements', f.replace('.clas.abap', '.clas.texts.md')))
            changed += write(p.replace('.clas.abap', '.clas.xml'), wrap('LCL_OBJECT_CLAS', body))
        elif f.endswith('.intf.abap'):
            text = open(p, encoding='utf-8').read()
            body = '   <VSEOINTERF>\n' + tag('CLSNAME', name) + tag('LANGU', 'E') + \
                   tag('DESCRIPT', description(text, name)) + tag('EXPOSURE', '2') + tag('STATE', '1') + \
                   tag('UNICODE', 'X') + '   </VSEOINTERF>\n'
            changed += write(p.replace('.intf.abap', '.intf.xml'), wrap('LCL_OBJECT_INTF', body))
        elif f.endswith('.prog.abap'):
            body = '   <PROGDIR>\n' + tag('NAME', name) + tag('SUBC', '1') + tag('RLOAD', 'E') + \
                   tag('FIXPT', 'X') + tag('UCCHECK', 'X') + '   </PROGDIR>\n'
            body += tpool(os.path.join(ROOT, 'docs', 'text_elements', f.replace('.prog.abap', '.prog.texts.md')))
            changed += write(p.replace('.prog.abap', '.prog.xml'), wrap('LCL_OBJECT_PROG', body))

# RAP sources (DDLS, DDLX, BDEF, SRVD). Formats taken from abapGit's serializers
# (zcl_abapgit_object_ddls/_ddlx/_bdef/_srvd) and files serialized by abapGit in
# SAP-samples/abap-platform-refscen-flight, branch ABAP-platform-2023.
def label_of(text, default):
    m = re.search(r"@EndUserText\.label\s*:\s*'([^']*)'", text)
    return (m.group(1) if m else default)[:60]

for d, _, files in os.walk(SRC):
    for f in sorted(files):
        p = os.path.join(d, f)
        name = f.split('.')[0].upper()
        low = f.split('.')[0].lower()
        if f.endswith('.ddls.asddls'):
            text = open(p, encoding='utf-8').read()
            kind = ('A' if re.search(r'\bdefine\s+abstract\s+entity\b', text, re.I)
                    else 'P' if re.search(r'\bas\s+projection\s+on\b', text, re.I) else 'W')
            body = '   <DDLS>\n' + tag('DDLNAME', name) + tag('DDLANGUAGE', 'E') + \
                   tag('DDTEXT', label_of(text, name)) + tag('SOURCE_TYPE', kind) + '   </DDLS>\n'
            changed += write(p.replace('.ddls.asddls', '.ddls.xml'), wrap('LCL_OBJECT_DDLS', body))
        elif f.endswith('.ddlx.asddlxs'):
            text = open(p, encoding='utf-8').read()
            m = re.search(r'^//\s*UI annotations:\s*(.*)$', text, re.M)
            desc = (m.group(1) if m else name)[:60]
            body = '   <DDLX>\n    <METADATA>\n' + tag('NAME', name, 5) + tag('DESCRIPTION', desc, 5) + \
                   tag('MASTER_LANGUAGE', 'EN', 5) + '    </METADATA>\n   </DDLX>\n'
            changed += write(p.replace('.ddlx.asddlxs', '.ddlx.xml'), wrap('LCL_OBJECT_DDLX', body))
        elif f.endswith('.bdef.asbdef'):
            src = f'./{low}/source/main'
            links = ''
            for href, rel, typ, title in (
                    (f'{src}/versions', 'http://www.sap.com/adt/relations/versions', None, 'Historic versions'),
                    (src, 'http://www.sap.com/adt/relations/source', 'text/plain', 'Source Content'),
                    (src, 'http://www.sap.com/adt/relations/source', 'text/html', 'Source Content (HTML)')):
                links += '     <item>\n' + tag('HREF', href, 6) + tag('REL', rel, 6) + \
                         (tag('TYPE', typ, 6) if typ else '') + tag('TITLE', title, 6) + '     </item>\n'
            body = '   <BDEF>\n' + tag('NAME', name) + tag('TYPE', 'BDEF/BDO') + \
                   tag('DESCRIPTION', f'Behavior for {name}'[:60]) + tag('DESCRIPTION_TEXT_LIMIT', '60') + \
                   tag('LANGUAGE', 'EN') + '    <LINKS>\n' + links + '    </LINKS>\n' + \
                   tag('MASTER_LANGUAGE', 'EN') + tag('ABAP_LANGU_VERSION', 'X') + tag('SOURCE_URI', src) + \
                   tag('SOURCE_TYPE', 'ABAP_SOURCE') + tag('SOURCE_FIXED_POINT_ARITHMETIC', 'true') + \
                   tag('SOURCE_UNICODE_CHECKS_ACTIVE', 'true') + '   </BDEF>\n'
            changed += write(p.replace('.bdef.asbdef', '.bdef.xml'), wrap('LCL_OBJECT_BDEF', body))
        elif f.endswith('.srvd.srvdsrv'):
            text = open(p, encoding='utf-8').read()
            body = '   <SRVD>\n' + tag('NAME', name) + tag('TYPE', 'SRVD/SRV') + \
                   tag('DESCRIPTION', label_of(text, name)) + tag('LANGUAGE', 'EN') + \
                   tag('MASTER_LANGUAGE', 'EN') + tag('SOURCE_URI', f'./{low}/source/main') + \
                   tag('SOURCE_TYPE', 'ABAP_SOURCE') + tag('SOURCE_ORIGIN_DESCRIPTION', 'ABAP Development Tools') + \
                   tag('SRVD_SOURCE_TYPE', 'S') + tag('SRVD_SOURCE_TYPE_DESC', 'Definition') + '   </SRVD>\n'
            changed += write(p.replace('.srvd.srvdsrv', '.srvd.xml'), wrap('LCL_OBJECT_SRVD', body))
        elif f.endswith('.dcls.asdcls'):
            # Access control (zcl_abapgit_object_dcls: structure ACM_S_DCLSRC without SOURCE and
            # user/date fields; the source stays in .asdcls). VERIFY-ADT: the first abapGit pull in
            # DV1 confirms the DCLS metadata (else create the role in ADT from the .asdcls source).
            text = open(p, encoding='utf-8').read()
            body = '   <DCLS>\n' + tag('DCLNAME', name) + tag('DESCRIPTION', label_of(text, name)) + '   </DCLS>\n'
            changed += write(p.replace('.dcls.asdcls', '.dcls.xml'), wrap('LCL_OBJECT_DCLS', body))

# tables from DDL
INCLUDE = re.compile(r'^\s*"(%\w+)"\s*:\s*include\s+(\w+)\s*;', re.I)
BUILTIN = {  # type -> (INTTYPE, intlen(fn of len), DATATYPE, leng(fn of len))
    'char': ('C', lambda n: 2 * n, 'CHAR', lambda n: n),
    'numc': ('N', lambda n: 2 * n, 'NUMC', lambda n: n),
    'clnt': ('C', lambda n: 6, 'CLNT', lambda n: 3),
    'dats': ('D', lambda n: 16, 'DATS', lambda n: 8),
    'tims': ('T', lambda n: 12, 'TIMS', lambda n: 6),
    'int1': ('b', lambda n: 1, 'INT1', lambda n: 3),
    'int2': ('s', lambda n: 2, 'INT2', lambda n: 5),
    'int4': ('X', lambda n: 4, 'INT4', lambda n: 10),
    'int8': ('8', lambda n: 8, 'INT8', lambda n: 19),
    'string': ('g', lambda n: 8, 'STRG', lambda n: 0),
}
FIELD = re.compile(r'^\s*(key\s+)?([a-z_0-9]+)\s*:\s*([a-z_0-9.]+)(?:\((\d+)(?:,(\d+))?\))?\s*(not null)?\s*;', re.I)
# Secondary indexes (audit A05): only DDL lines '// @index <ID> [UNIQUE]: F1, F2' are serialized,
# so tables without the marker keep byte-identical XML. abapGit TABL layout (zcl_abapgit_object_tabl,
# lcl_tabl_xml=>add): DD12V then DD17V after DD03P_TABLE, one row element per line type.
# VERIFY-ADT: the first abapGit pull in DV1 confirms the index is created (SE11 -> Indexes).
INDEX = re.compile(r'^\s*//\s*@index\s+(\w{1,3})\s*(UNIQUE)?\s*:\s*(.+?)\s*$', re.I | re.M)


def index_xml(tab, text, names, problems, f):
    head, items = '', ''
    seen = set()
    for idx, unique, cols in INDEX.findall(text):
        cols_list = [c.strip().upper() for c in cols.split(',') if c.strip()]
        bad = [c for c in cols_list if c not in names]
        if idx.upper() in seen or not cols_list or bad:
            problems.append(f'{f}: index {idx} duplicate, empty or unknown field(s) {bad}')
            continue
        seen.add(idx.upper())
        head += ('    <DD12V>\n' + tag('SQLTAB', tab, 5) + tag('INDEXNAME', idx.upper(), 5) +
                 tag('AS4LOCAL', 'A', 5) + tag('DDLANGUAGE', 'E', 5) +
                 (tag('UNIQUEFLAG', 'X', 5) if unique else '') +
                 tag('DDTEXT', f'{tab}~{idx.upper()}', 5) + '    </DD12V>\n')
        for pos, col in enumerate(cols_list, start=1):
            items += ('    <DD17V>\n' + tag('SQLTAB', tab, 5) + tag('INDEXNAME', idx.upper(), 5) +
                      tag('POSITION', f'{pos:04d}', 5) + tag('AS4LOCAL', 'A', 5) +
                      tag('FIELDNAME', col.upper(), 5) + '    </DD17V>\n')
    if not head:
        return ''
    return '   <DD12V>\n' + head + '   </DD12V>\n   <DD17V>\n' + items + '   </DD17V>\n'

unknown = []
for pe_area in ('core', 'ebs', 'fmon', 'hck'):
    ddic = os.path.join(ROOT, 'ddic', pe_area)
    if not os.path.isdir(ddic):
        continue
    for f in sorted(os.listdir(ddic)):
        if not f.endswith('.tabl.ddl'):
            continue
        text = open(os.path.join(ddic, f), encoding='utf-8').read()
        heads = (re.search(r'define table (\w+)', text),
                 re.search(r"@EndUserText.label\s*:\s*'([^']*)'", text),
                 re.search(r'deliveryClass\s*:\s*#(\w)', text),
                 re.search(r'dataMaintenance\s*:\s*#(\w+)', text))
        if not all(heads) or '{' not in text or '}' not in text:
            unknown.append(f'{f}: table name, label, delivery class, maintenance or field block missing')
            continue
        tab = heads[0].group(1).upper()
        label = heads[1].group(1)[:60]
        dclass = heads[2].group(1)
        maint = heads[3].group(1)
        fields, names = [], set()
        for line in text.split('{', 1)[1].split('}', 1)[0].splitlines():
            line = line.split('//')[0]
            inc = INCLUDE.match(line)
            if inc:  # draft admin include (sample: refscen-flight 2023 draft tables)
                fields.append('    <DD03P>\n' + tag('FIELDNAME', '.INCLUDE', 5) + tag('ADMINFIELD', '0', 5) +
                              tag('PRECFIELD', inc.group(2).upper(), 5) + tag('MASK', '      S', 5) +
                              tag('DDTEXT', 'Standard Include for Draft Administration (BDL Syntax Check)', 5) +
                              tag('COMPTYPE', 'S', 5) + tag('GROUPNAME', inc.group(1).upper(), 5) +
                              '    </DD03P>\n')
                continue
            m = FIELD.match(line)
            if not m:
                if line.strip():
                    unknown.append(f'{f}: {line.strip()}')
                continue
            key, fname, ftype, length, decimals, notnull = m.groups()
            names.add(fname.upper())
            fx = '    <DD03P>\n' + tag('FIELDNAME', fname.upper(), 5)
            if key:
                fx += tag('KEYFLAG', 'X', 5)
            if ftype.startswith('abap.') and ftype[5:] != 'dec':
                kind = ftype[5:]
                if kind not in BUILTIN:
                    unknown.append(f'{f}: {fname} {ftype}')
                    continue
                inttype, intlen, datatype, leng = BUILTIN[kind]
                n = int(length or 0)
                fx += tag('ADMINFIELD', '0', 5) + tag('INTTYPE', inttype, 5) + \
                      tag('INTLEN', f'{intlen(n):06d}', 5)
                if key or notnull:
                    fx += tag('NOTNULL', 'X', 5)
                fx += tag('DATATYPE', datatype, 5) + tag('LENG', f'{leng(n):06d}', 5) + \
                      tag('MASK', f'  {datatype}', 5)
            elif ftype == 'abap.dec':
                n, dec = int(length), int(decimals or 0)
                fx += tag('ADMINFIELD', '0', 5) + tag('INTTYPE', 'P', 5) + tag('INTLEN', f'{n // 2 + 1:06d}', 5)
                if key or notnull:
                    fx += tag('NOTNULL', 'X', 5)
                fx += tag('DATATYPE', 'DEC', 5) + tag('LENG', f'{n:06d}', 5) + \
                      tag('DECIMALS', f'{dec:06d}', 5) + tag('MASK', '  DEC', 5)
            else:  # data element
                fx += tag('ROLLNAME', ftype.upper(), 5) + tag('ADMINFIELD', '0', 5)
                if key or notnull:
                    fx += tag('NOTNULL', 'X', 5)
                fx += tag('COMPTYPE', 'E', 5)
            fields.append(fx + '    </DD03P>\n')
        customizing = dclass == 'C'
        body = ('   <DD02V>\n' + tag('TABNAME', tab) + tag('DDLANGUAGE', 'E') + tag('TABCLASS', 'TRANSP') +
                tag('CLIDEP', 'X') + tag('DDTEXT', label) +
                tag('MAINFLAG', 'X' if maint.upper() == 'ALLOWED' else '') + tag('CONTFLAG', dclass) +
                tag('EXCLASS', '1') + '   </DD02V>\n'
                '   <DD09L>\n' + tag('TABNAME', tab) + tag('AS4LOCAL', 'A') + tag('TABKAT', '0') +
                tag('TABART', 'APPL2' if customizing else 'APPL1') +
                # Review 3.5: customizing tables fully buffered by the kernel, not cached in ABAP
                (tag('PUFFERUNG', 'X') if customizing else '') +
                # SOX: changes to rules, maps, thresholds and alert routing are logged (SCU3);
                # needs profile parameter rec/client set by Basis
                (tag('PROTOKOLL', 'X') if customizing else '') +
                tag('BUFALLOW', 'X' if customizing else 'N') + '   </DD09L>\n'
                '   <DD03P_TABLE>\n' + ''.join(fields) + '   </DD03P_TABLE>\n' + index_xml(tab, text, names, unknown, f))
        target = os.path.join(SRC, pe_area, f.replace('.tabl.ddl', '.tabl.xml'))
        changed += write(target, wrap('LCL_OBJECT_TABL', body))

# message class
rows = re.findall(r'^\| (\d{3}) \| (.*?) \|$', open(os.path.join(ROOT, 'config', 'zcd_ops_messages.md'),
                                                     encoding='utf-8').read(), re.M)
body = '   <T100A>\n' + tag('ARBGB', 'ZCD_OPS') + tag('MASTERLANG', 'E') + \
       tag('STEXT', 'Payment engine operations suite') + '   </T100A>\n   <T100>\n'
for nr, text in rows:
    body += '    <T100>\n' + tag('SPRSL', 'E', 5) + tag('ARBGB', 'ZCD_OPS', 5) + tag('MSGNR', nr, 5) + \
            tag('TEXT', text[:73], 5) + '    </T100>\n'
body += '   </T100>\n'
changed += write(os.path.join(SRC, 'core', 'zcd_ops.msag.xml'), wrap('LCL_OBJECT_MSAG', body))

if unknown:
    print('NOT SERIALIZED - no file written (check):', *unknown, sep='\n  ')
    sys.exit(1)
flush()
print(f'{changed} file(s) written/updated; {len(rows)} messages')
