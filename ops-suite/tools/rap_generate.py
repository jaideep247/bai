def bdef_r(app, tables):
    root, low = app['root'], app['root'].lower()
    out = [f"managed implementation in class zbp_r_cd_{low} unique;",
           'strict ( 2 );',
           'with draft;',
           '',
           f"// {app['title']}: singleton root (virtual, nothing persisted) - lock, total ETag,",
           '// draft and the customizing request; every customizing table is a child.',
           f"define behavior for ZR_CD_{root} alias {root}",
           'with unmanaged save',
           f"draft table {app['draft']}",
           'lock master',
           'total etag LastChangedAtMax',
           'authorization master ( global )',
           '##DRAFT_OP_NOT_REQUIRED',
           '{',
           '  update;',
           '  field ( readonly ) SingletonID, LastChangedAtMax;',
           '']
    for t in tables:
        out.append(f"  association _{t['alias']} {{ create ( features : global ); with draft; }}")
    out += ['', '  draft action Edit;', '  draft action Activate optimized;', '  draft action Discard;',
            '  draft action Resume;', '  draft determine action Prepare', '  {']
    for t in tables:
        if t['checks']:
            out.append(f"    validation {t['alias']} ~ validateFields;")
        out.append(f"    validation {t['alias']} ~ validateTransport;")
    out += ['  }', '}']
    for t in tables:
        f_all = t['fields']
        keys = [f for f in f_all if f['key']]
        mand = [f['el'] for f in keys if f['name'] not in t['blank_keys']]
        ro = ['SingletonID'] + [f['el'] for f in f_all if f['name'] in ADMIN + LEGACY_ADMIN]
        out += ['',
                f"define behavior for ZR_CD_{t['alias']} alias {t['alias']}",
                f"persistent table {t['table']}",
                'with additional save',
                f"draft table {t['draft']}",
                f"lock dependent by _{root}",
                f"authorization dependent by _{root}",
                'etag master LocalLastChangedAt',
                '{',
                '  update;',
                '  delete ( features : global );',
                f"  field ( readonly ) {', '.join(ro)};",
                f"  field ( readonly : update ) {', '.join(f['el'] for f in keys)};"]
        if mand:
            out.append(f"  field ( mandatory : create ) {', '.join(mand)};")
        out.append(f"  association _{root} {{ with draft; }}")
        if t['checks']:
            out.append('  validation validateFields on save { create; update; }')
        out.append('  // VERIFY-ADT: delete as trigger of a validation (transport check of deletions)')
        out.append('  validation validateTransport on save { create; update; delete; }')
        out.append(f"  mapping for {t['table']}")
        out.append('  {')
        maps = [f"    {f['el']} = {f['name']};" for f in f_all]
        out += maps
        out.append('  }')
