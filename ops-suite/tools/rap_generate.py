FIELD = re.compile(r'^\s*(key\s+)?([a-z_0-9]+)\s*:\s*([a-z_0-9.]+(?:\(\d+(?:,\d+)?\))?)\s*(not null)?\s*;', re.I)


def camel(field):
    return RENAME.get(field, ''.join(p.capitalize() for p in field.split('_')))


def label(field):
    if field in LABELS:
        return LABELS[field]
    words = [TOKENS.get(p, p) for p in field.split('_')]
    text = ' '.join(words)
    return (text[0].upper() + text[1:])[:60]


def read_table(pe_area, table):
    text = open(os.path.join(ROOT, 'ddic', pe_area, table + '.tabl.ddl'), encoding='utf-8').read()
    fields = []
    for line in text.split('{', 1)[1].split('}', 1)[0].splitlines():
        m = FIELD.match(line.split('//')[0])
        if m and m.group(2) != 'mandt':
            fields.append(dict(key=bool(m.group(1)), name=m.group(2), type=m.group(3)))
    return fields


def write(rel, text):
    path = os.path.join(ROOT, rel)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    if not os.path.exists(path) or open(path, encoding='utf-8').read() != text:
        open(path, 'w', encoding='utf-8', newline='\n').write(text)
        return 1
    return 0


