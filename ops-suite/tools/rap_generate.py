def abap_check(t, chk, root):
    """ABAP lines appending field messages for one check of one row (ls_row)."""
    fmap = {f['name']: f['el'] for f in t['fields']}
    kind = chk[0]
    msg = 'zif_cd_ops_cfg_types=>gc_msg-'
    if kind == 'enum':
        e, allowed = fmap[chk[1]], chk[2]
        lst = const('val', f"{t['alias']}_{e}"[:30], allowed)
        return [f"    IF zcl_cd_ops_cfg_checks=>in_list( iv_value = CONV #( ls_row-{e} )",
                f"                                      iv_list  = {lst} ) = abap_false.",
                f"      INSERT VALUE #( number = {msg}value_invalid v1 = ls_row-{e}",
                f"                      v2 = {el(e)} v3 = {lst}",
                f"                      element = {el(e)} ) INTO TABLE lt_msg.",
                '    ENDIF.']
    if kind == 'class':
        e, intf = fmap[chk[1]], chk[2]
        ic = const('if', intf, intf)
        return [f"    IF ls_row-{e} IS NOT INITIAL",
                f"       AND zcl_cd_ops_cfg_checks=>implements( iv_class     = CONV #( ls_row-{e} )",
                f"                                              iv_interface = CONV #( {ic} ) ) = abap_false.",
                f"      INSERT VALUE #( number = {msg}class_invalid v1 = ls_row-{e} v2 = {ic}",
                f"                      element = {el(e)} ) INTO TABLE lt_msg.",
                '    ENDIF.']
    if kind == 'table':
        e = fmap[chk[1]]
        return [f"    IF ls_row-{e} IS NOT INITIAL",
                f"       AND zcl_cd_ops_cfg_checks=>table_exists( CONV #( ls_row-{e} ) ) = abap_false.",
                f"      INSERT VALUE #( number = {msg}table_invalid v1 = ls_row-{e}",
                f"                      element = {el(e)} ) INTO TABLE lt_msg.",
                '    ENDIF.']
    if kind == 'field':
        e, tab = fmap[chk[1]], fmap[chk[2]]
        return [f"    IF ls_row-{e} IS NOT INITIAL AND ls_row-{tab} IS NOT INITIAL",
                f"       AND zcl_cd_ops_cfg_checks=>field_exists( iv_table = CONV #( ls_row-{tab} )",
                f"                                                iv_field = CONV #( ls_row-{e} ) ) = abap_false.",
                f"      INSERT VALUE #( number = {msg}field_invalid v1 = ls_row-{e} v2 = ls_row-{tab}",
                f"                      element = {el(e)} ) INTO TABLE lt_msg.",
                '    ENDIF.']
    if kind == 'window':
        a, b = fmap[chk[1]], fmap[chk[2]]
        return [f"    IF zcl_cd_ops_cfg_checks=>window_complete( iv_from = ls_row-{a}",
                f"                                              iv_to   = ls_row-{b} ) = abap_false.",
                f"      INSERT VALUE #( number = {msg}window_incomplete v1 = {el(a)} v2 = {el(b)}",
                f"                      element = {el(b)} ) INTO TABLE lt_msg.",
                '    ENDIF.']
    if kind == 'pcre':
        e = fmap[chk[1]]
        return [f"    IF zcl_cd_ops_util=>pcre_valid( ls_row-{e} ) = abap_false.",
                f"      INSERT VALUE #( number = {msg}pattern_invalid v1 = ls_row-{e}",
                f"                      element = {el(e)} ) INTO TABLE lt_msg.",
                '    ENDIF.']
    if kind == 'positive':
        e = fmap[chk[1]]
        return [f"    IF ls_row-{e} <= 0.",
                f"      INSERT VALUE #( number = {msg}not_positive v1 = {el(e)} element = {el(e)} )",
                '        INTO TABLE lt_msg.',
                '    ENDIF.']
    if kind == 'thresholds':
        return ["    IF zcl_cd_ops_cfg_checks=>thresholds_ordered( iv_amber           = CONV #( ls_row-Amber )",
                "                                                 iv_red             = CONV #( ls_row-Red )",
                "                                                 iv_higher_is_worse = ls_row-HigherIsWorse )",
                '       = abap_false.',
                f"      INSERT VALUE #( number = {msg}thresholds_order v1 = ls_row-Amber v2 = ls_row-Red",
                f"                      v3 = ls_row-Metric element = {el('Red')} ) INTO TABLE lt_msg.",
                '    ENDIF.']
    if kind == 'rulegroups':
        return ["    \" An active row that is not BLOCK needs a rule group (blank = category) with an active rule",
                "    DATA(lv_group) = COND zif_cd_ops_cfg_types=>ty_name( WHEN ls_row-RuleGroup IS INITIAL",
                "                                                         THEN ls_row-Category",
                "                                                         ELSE ls_row-RuleGroup ).",
                "    IF ls_row-Active = abap_true AND ls_row-ActionCode <> zif_cd_ops_types=>gc_action-block",
                "       AND zcl_cd_ops_cfg_checks=>missing_names( it_needed    = VALUE #( ( lv_group ) )",
                "                                                 it_available = lt_groups ) IS NOT INITIAL.",
                f"      INSERT VALUE #( number = {msg}rule_group_empty v1 = lv_group",
                f"                      element = {el('RuleGroup')} ) INTO TABLE lt_msg.",
                '    ENDIF.']
    raise ValueError(chk)


