#!/usr/bin/env python3
"""Generate RAP configuration apps (business-configuration maintenance objects) from the
customizing-table DDLs of a component - shared engine (tools/abaptools).

Each component's wrapper tools/rap_generate.py holds its profile (configure( ): ROOT, SPEC, RENAME,
TOKENS, LABELS) and calls main( ): the operations framework's app ZUI_CA_OPS_CFG (prefix CA) from
ops-framework/tools/rap_generate.py, a consumer's apps (prefix CD) from its own wrapper.

Shape (SAP business-configuration maintenance object, ABAP platform 2023):
singleton root (virtual, unmanaged save, SingletonID = 1, draft) with every
customizing table of the app's area as a child (managed, persistent table, draft,
additional save for transport recording). One service per app.

Writes (checked in, regenerate after a table change; names shown with prefix CD):
  ddic/<mod>/zcd_d_<x>.tabl.ddl                draft tables (root + children)
  src/<mod>/zr_cd_*.ddls.asddls / zc_cd_*      CDS view entities (R / C)
  src/<mod>/zi_cd_<mod>cfgchg.ddls.asddls      change stamps (union) -> total ETag
  src/<mod>/zc_cd_*.ddlx.asddlxs               UI annotations
  src/<mod>/zr_cd_<root>.bdef.asbdef / zc_...  behaviour definitions
  src/<mod>/zui_cd_<mod>_cfg.srvd.srvdsrv      service definition
  src/<mod>/zbp_r_cd_<root>.clas.abap/.locals_imp.abap   behaviour pool
  src/<mod>/zbp_r_cd_<root>.clas.testclasses.abap        authorization tests (EML GET PERMISSIONS)
Then run tools/abapgit_serialize.py for the abapGit XML.

Each app names its base folder (base, relative to the component folder, default the folder
itself), its DDIC / source sub-folders and its prefix (CD or CA): names, the field-check message
types and the message class follow the prefix (LOCALIZE). Generic checks call the framework
(ZCL_CA_OPS_CFG_CHECKS, ZCL_CA_OPS_UTIL); the consumer-specific check kinds (thresholds,
approved, valid) call the consumer.

Usage (from the component folder): python3 tools/rap_generate.py [--check]

Modification log:
2026-11-06 | Initial version (RAP configuration apps, design 5).
2026-11-10 | Parameterised for the framework ZCA_OPS (prefix CA, area checks, authorisation ZCA_OPS).
2026-11-10 | Moved to the shared tools (tools/abaptools): the engine only; each component's wrapper holds
           | its apps (the framework's own app is generated from ops-framework). Output unchanged.
"""
