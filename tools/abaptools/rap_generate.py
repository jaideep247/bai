def draft_table(name, label_text, fields):
    lines = [f"@EndUserText.label : '{label_text[:60]}'",
             '@AbapCatalog.enhancement.category : #NOT_EXTENSIBLE',
             '@AbapCatalog.tableCategory : #TRANSPARENT',
             '@AbapCatalog.deliveryClass : #A',
             '@AbapCatalog.dataMaintenance : #RESTRICTED',
             f'define table {name} {{',
             '  key mandt : abap.clnt not null;']
    for f in fields:
        lines.append(f"  {'key ' if f['key'] else ''}{f['el'].lower()} : {f['type']}{' not null' if f['key'] else ''};")
    lines.append('  "%admin" : include sych_bdl_draft_admin_inc;')
    lines.append('}')
    return '\n'.join(lines) + '\n'


def child_r(app, t, fields):
    rootname = f"ZR_CD_{app['root']}"
    out = ['@AccessControl.authorizationCheck: #NOT_REQUIRED',
           f"@EndUserText.label: '{t['plural']}'",
           '@Metadata.ignorePropagatedAnnotations: true',
           f"define view entity ZR_CD_{t['alias']}",
           f"  as select from {t['table']}",
           f"  association to parent {rootname} as _{app['root']} on $projection.SingletonID = _{app['root']}.SingletonID",
           '{']
    for f in fields:
        if f['key']:
            out.append(f"      @EndUserText.label: '{label(f['name'])}'")
            out.append(f"  key {f['name']} as {f['el']},")
    out.append('      1 as SingletonID,')
    for f in fields:
        if f['key']:
            continue
        if f['name'] == 'last_changed_by':
            out.append('      @Semantics.user.lastChangedBy: true')
        elif f['name'] == 'last_changed_at':
            out.append('      @Semantics.systemDateTime.lastChangedAt: true')
        elif f['name'] == 'local_last_changed_at':
            out.append('      @Semantics.systemDateTime.localInstanceLastChangedAt: true')
        out.append(f"      @EndUserText.label: '{label(f['name'])}'")
        out.append(f"      {f['name']} as {f['el']},")
    out.append(f"      _{app['root']}")
    out.append('}')
    return '\n'.join(out) + '\n'


def child_c(app, t, fields):
    keys = ', '.join(f"'{f['el']}'" for f in fields if f['key'])
    out = ['@AccessControl.authorizationCheck: #NOT_REQUIRED',
           f"@EndUserText.label: '{t['plural']}'",
           '@Metadata.allowExtensions: true',
           f'@ObjectModel.semanticKey: [{keys}]',
           f"define view entity ZC_CD_{t['alias']}",
           f"  as projection on ZR_CD_{t['alias']}",
           '{']
    for f in fields:
        if f['key']:
            out.append(f"  key {f['el']},")
    out.append('      @Consumption.hidden: true')
    out.append('      SingletonID,')
    for f in fields:
        if not f['key']:
            out.append(f"      {f['el']},")
    out.append(f"      _{app['root']} : redirected to parent ZC_CD_{app['root']}")
    out.append('}')
    return '\n'.join(out) + '\n'


def child_ddlx(app, t, fields):
    visible = [f for f in fields if f['name'] not in ADMIN + LEGACY_ADMIN]
    first = next(f for f in fields if f['key'])
    out = [f"// UI annotations: {app['title']} - {t['plural']}",
           '@Metadata.layer: #CORE',
           f"@UI: {{ headerInfo: {{ typeName: '{t['singular']}',",
           f"                     typeNamePlural: '{t['plural']}',",
           f"                     title: {{ type: #STANDARD, value: '{first['el']}' }} }} }}",
           f"annotate entity ZC_CD_{t['alias']} with",
           '{',
           "  @UI.facet: [ { id: 'Details', purpose: #STANDARD, type: #IDENTIFICATION_REFERENCE,",
           "                label: 'Details', position: 10 } ]"]
    for i, f in enumerate(visible, start=1):
        pos = i * 10
        line_item = f'@UI.lineItem: [{{ position: {pos} }}]' if i <= 8 else ''
        out.append('')
        if line_item:
            out.append(f'  {line_item}')
        out.append(f'  @UI.identification: [{{ position: {pos} }}]')
        out.append(f"  {f['el']};")
    for f in fields:
        if f['name'] in ADMIN + LEGACY_ADMIN:
            out.append('')
            out.append('  @UI.hidden: true')
            out.append(f"  {f['el']};")
    out.append('}')
    return '\n'.join(out) + '\n'


def root_r(app, tables):
    out = ['@AccessControl.authorizationCheck: #NOT_REQUIRED',
           f"@EndUserText.label: '{app['title']} (all)'",
           f"define root view entity ZR_CD_{app['root']}",
           '  as select from I_Language',
           f"    left outer join ZI_CD_{app['chg']} as Chg on 0 = 0"]
    for t in tables:
        out.append(f"  composition [0..*] of ZR_CD_{t['alias']} as _{t['alias']}")
    out += ['{',
            '  key 1 as SingletonID,',
            '      max( Chg.LastChangedAt ) as LastChangedAtMax,',
            "      @EndUserText.label: 'Customizing request'",
            "      cast( '' as trkorr ) as TransportRequestID,"]
    out += [f"      _{t['alias']}," for t in tables]
    out[-1] = out[-1].rstrip(',')
    out += ['}', 'where', '  I_Language.Language = $session.system_language']
    return '\n'.join(out) + '\n'


def chg_view(app, tables):
    out = ['@AccessControl.authorizationCheck: #NOT_REQUIRED',
           f"@EndUserText.label: '{app['title']}: change stamps'",
           '// Union of LAST_CHANGED_AT of every table of the app: total ETag of the singleton root.',
           '// VERIFY-ADT: UNION in CDS view entities (ABAP platform 2023).',
           f"define view entity ZI_CD_{app['chg']}"]
    for i, t in enumerate(tables):
        prefix = '  as select from' if i == 0 else 'union all\n  select from'
        out.append(f"{prefix} {t['table']}")
        out.append('  {')
        out.append('    last_changed_at as LastChangedAt')
        out.append('  }')
    return '\n'.join(out) + '\n'


