BLANK, FILLED = '<blank>', '<filled>'
# Profile (configure( ) of the wrapper): ROOT component folder; SPEC the apps; RENAME element names
# that would collide with RAP / BDEF keywords; TOKENS words of a field name -> label words; LABELS
# field -> label (overrides TOKENS)
SPEC = {}
RENAME = {}
TOKENS = {}
LABELS = {}

ADMIN = ('last_changed_by', 'last_changed_at', 'local_last_changed_at')
LEGACY_ADMIN = ('changed_by', 'changed_at')

FIELD = re.compile(r'^\s*(key\s+)?([a-z_0-9]+)\s*:\s*([a-z_0-9.]+(?:\(\d+(?:,\d+)?\))?)\s*(not null)?\s*;', re.I)


def camel(field):
    return RENAME.get(field, ''.join(p.capitalize() for p in field.split('_')))


def label(field):
    if field in LABELS:
        return LABELS[field]
    words = [TOKENS.get(p, p) for p in field.split('_')]
    text = ' '.join(words)
    return (text[0].upper() + text[1:])[:60]


def base(app):
    """Folder of an app's component (the wrapper's folder, or the app's base relative to it)."""
    return os.path.normpath(os.path.join(ROOT, app.get('base', '.')))


def localize(text, app):
    """The suite's names (prefix CD) become the framework's (prefix CA) for an app of the framework."""
    if app.get('prefix', 'cd') == 'cd':
        return text
    for old, new in (('ZR_CD_', 'ZR_CA_'), ('ZC_CD_', 'ZC_CA_'), ('ZI_CD_', 'ZI_CA_'), ('zr_cd_', 'zr_ca_'),
                     ('zc_cd_', 'zc_ca_'), ('zi_cd_', 'zi_ca_'), ('zbp_r_cd_', 'zbp_r_ca_'),
                     ('lsc_zr_cd_', 'lsc_zr_ca_'), ('zif_cd_ops_cfg_types=>gc_msg', 'zif_ca_ops_cfg_types=>gc_msg'),
                     ('zif_cd_ops_types=>gc_message_class', 'zif_ca_ops_types=>gc_message_class'),
                     ('ZCL_CD_OPS_CFG_CHECKS', 'ZCL_CA_OPS_CFG_CHECKS')):
        text = text.replace(old, new)
    return text


def read_table(app, table):
    text = open(os.path.join(base(app), 'ddic', app['ddic'], table + '.tabl.ddl'), encoding='utf-8').read()
    fields = []
    for line in text.split('{', 1)[1].split('}', 1)[0].splitlines():
        m = FIELD.match(line.split('//')[0])
        if m and m.group(2) != 'mandt':
            fields.append(dict(key=bool(m.group(1)), name=m.group(2), type=m.group(3)))
    return fields


CHECK_ONLY = False
STALE = []


def write(rel, text, app=None):
    rel = localize(rel, app) if app else rel
    path = os.path.normpath(os.path.join(base(app) if app else ROOT, rel))
    text = localize(text, app) if app else text
    if CHECK_ONLY:
        if not os.path.exists(path) or open(path, encoding='utf-8').read() != text:
            STALE.append(os.path.relpath(path, ROOT))
            return 1
        return 0
    os.makedirs(os.path.dirname(path), exist_ok=True)
    if not os.path.exists(path) or open(path, encoding='utf-8').read() != text:
        open(path, 'w', encoding='utf-8', newline='\n').write(text)
        return 1
    return 0


